"""Narrow runtime dependencies of autoclose, independent of application assembly."""
from typing import Callable, Protocol

from walletwatcher.domain.credentials import Credentials


class CredentialReader(Protocol):
    def load(self, user: int) -> Credentials | None: ...

    def version(self, user: int) -> str | None: ...


class RuleAccess(Protocol):
    @property
    def poll_interval(self) -> float: ...

    def allows_user(self, user: int) -> bool: ...

    def tracks_wallet(self, wallet: str) -> bool: ...


class TradingRequests(Protocol):
    """Shared request accounting and per-thread priority, without exchange HTTP."""

    def set_heartbeat(self, callback: Callable[[], None]) -> None: ...

    def set_trading_priority(self, enabled: bool) -> None: ...

    def set_trading_rule(self, rule_id: str) -> None: ...

    def set_close_priority(self, rule_id: str, enabled: bool) -> None: ...

    def sync_close_priorities(self, rule_ids: set[str]) -> None: ...

    def reserve_for_trading(self, enabled: bool) -> None: ...

    def begin_trading_cycle(self) -> None: ...

    def finish_trading_cycle(self, active_rules: set[str]) -> None: ...

    def schedule_trading_check(self, weight: int, delay: float, *,
                               interval: float, recurring: int) -> None: ...
